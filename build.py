# У каждой позиции казахстанского каталога есть готовое авторское
# описание — точнее и нашего шаблона, и куцых текстов из выгрузки.
# Поэтому оно первый источник, выгрузка второй, шаблон последний.
# Соответствие ищем по набору значимых слов названия, чтобы
# «Камин Дорф, Муравленый» нашёл «Камин Дорф Муравленый».
KZ_SKIP = {'с', 'и', 'в', 'на', 'для', 'из', 'от', 'по'}


def _key_words(v):
    ws = re.findall(r'[а-яёa-z]+', (v or '').lower())
    return frozenset(w for w in ws if w not in KZ_SKIP)


def _load_kz():
    path = os.path.join(ROOT, 'kz_descriptions.json')
    if not os.path.exists(path):
        return []
    rows = json.load(io.open(path, encoding='utf-8'))
    # Имя чистим теми же правилами, что и текст из выгрузки: иначе
    # «Эксклюзивная кухня» не сходится с «Кухня с мангалом», у которой
    # эпитет уже снят, и позиция остаётся без своего описания.
    return [(x['cat'],
             _key_words(clean_text(x['name'], x['name'])),
             (x.get('full') or x.get('desc') or '').strip())
            for x in rows]


_KZ_CACHE = []


def KZ_DESC():
    """Загружается лениво: clean_text объявлен ниже по файлу."""
    if not _KZ_CACHE:
        _KZ_CACHE.extend(_load_kz())
    return _KZ_CACHE


# Каталог kz состоит из двух разделов, и совпадение ищем только внутри
# своего. Иначе «Печь-камин Дорф, Белый Антик» — заводская модель из
# наличия — цепляет описание каминного проекта для ресторана просто
# потому, что в обоих названиях есть «камин» и «Дорф».
KZ_CAT = {'kaminy': 'kaminy', 'barbekyu-kompleksy': 'bbq'}


def assign_kz(slug, cards):
    """Описания kz-каталога раздаём карточкам однозначно.

    Одно описание не может достаться двум карточкам: «Камин Альбион» и
    «Камин Альбион, майоликовая глазурь» оба подходят под запись
    «Камин Альбион», и без распределения обе получают один текст —
    а поздний проход по дублям затирает его заглушкой.

    Ключом берём итоговое название, исходное из выгрузки и её же
    короткое описание. Название после шаблона «тип + коллекция» теряет
    слово, по которому позиция узнаётся («Биокамин Альбион» → «Камин
    Альбион, глазурь»), а у части объектов имя каталога вообще лежит в
    описании: позиция 7 барбекю названа просто «Дорф», и узнать в ней
    «Эксклюзивную кухню» можно только по описанию. Без этого ключа она
    цепляла чужой текст про зелёные изразцы, а на фото коричневые.
    """
    cat = KZ_CAT.get(slug)
    if not cat:
        return cards
    pairs = []
    for ci, c in enumerate(cards):
        if c.get('_lock'):
            continue
        keys = [_key_words(c.get('title')), _key_words(c.get('_raw')),
                _key_words(c.get('_srcdesc'))]
        for ki, (kcat, words, text) in enumerate(KZ_DESC()):
            if not text or kcat != cat:
                continue
            best = None
            for k in keys:
                if not k or not (words <= k or k <= words):
                    continue
                common = len(words & k)
                if common < 2:
                    continue
                rank = (common, -len(words ^ k))
                if best is None or rank > best:
                    best = rank
            if best:
                pairs.append((best, ci, ki))
    pairs.sort(key=lambda x: x[0], reverse=True)
    used_c, used_k = set(), set()
    for _, ci, ki in pairs:
        if ci in used_c or ki in used_k:
            continue
        txt = normalize_brand(clean_text(KZ_DESC()[ki][2], ''))
        if not txt:
            continue
        used_c.add(ci)
        used_k.add(ki)
        cards[ci]['desc'] = txt
        cards[ci]['_gen'] = False
        # Номер позиции kz-каталога: по нему берутся местные цены.
        cards[ci]['_kz'] = ki
    return cards


def fit(v, limit, hard=None):
    """Оставляем целые предложения — никогда не рвём на полуслове.

    Многоточие в конце карточки читается как обрыв связи, а не как
    продолжение: «печь под казан и вместительный…». Поэтому берём
    столько целых предложений, сколько помещается, и только если даже
    первое длиннее жёсткого потолка — режем по слову.
    """
    v = (v or '').strip()
    hard = hard or int(limit * 1.35)
    if len(v) <= limit:
        return v
    ends = [m.end() for m in re.finditer(r'[.!?](?:\s|$)', v)]
    fits = [i for i in ends if i <= hard]
    if fits:
        return v[:max(fits)].strip()
    i = v[:hard + 1].rfind(' ')
    return (v[:i] if i > 40 else v[:hard]).rstrip(' ,.;:—-') + '…'


def normalize_brand(v):
    """Бренд пишется в два слова. В выгрузке встречается слитно
    кириллицей — «КерамикаДекор», это читается как опечатка."""
    v = re.sub(r'[Кк]ерамика[Дд]екор', 'Ceramica Decor', v or '')
    # и латиницей: в выгрузке встречается «CeramicaDecor» слитно
    return re.sub(r'\bCeramicaDecor\b', 'Ceramica Decor', v)


def clean_text(v, fallback=""):
    """Убирает из выгрузки ссылки, служебный мусор и рекламные эпитеты.
    Дирекция запрещает прилагательные: материальность доказывается
    размерностью — сантиметрами, килограммами, штуками."""
    v = (v or "").strip()
    low = v.lower()
    for wbad in BANNED_WORDS:
        if low.startswith(wbad):
            # «Эксклюзивная кухня…» → «Кухня…»
            v = v.split(' ', 1)[1] if ' ' in v else v
            v = v[:1].upper() + v[1:]
            low = v.lower()
    for wbad in BANNED_WORDS:
        i = low.find(' ' + wbad)
        if i > 0:
            end = v.find(' ', i + 1)
            v = (v[:i] + (v[end:] if end > 0 else '')).strip()
            low = v.lower()
    if not v or v.startswith("http") or "ceramicadecor.ru/" in v or v.startswith("cd_"):
        return fallback
    # хвост вида «| Ceramica Decor» в описании ничего не добавляет
    v = v.split("|")[0].strip()
    # Снятый эпитет мог открывать предложение: «…облицовке Птицы.
    # ручная роспись…». Поднимаем регистр обратно.
    v = re.sub(r'([.!?]\s+)([а-яё])', lambda m: m.group(1) + m.group(2).upper(), v)
    # Прямые кавычки из выгрузки — на ёлочки: на странице всё остальное
    # набрано ими.
    v = re.sub(r'"([^"]+)"', '\u00ab\\1\u00bb', v)
    for a, b in TYPOS:
        if a != b:
            v = v.replace(a, b).replace(a.capitalize(), b.capitalize())
    return v or fallback


