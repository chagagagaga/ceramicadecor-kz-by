def facts_spec(facts):
    """Габариты и вес из таблицы характеристик.

    У печей-каминов из наличия в выгрузке размеров нет вообще, и карточка
    объекта открывалась без единой цифры. На странице модели они есть —
    строкой вида «730x1100x575мм».
    """
    out = {}
    m = re.search(r'(\d{3,4})\s*[xх]\s*(\d{3,4})\s*[xх]\s*(\d{3,4})',
                  facts.get('Габаритные размеры (ШхВхГ)') or '')
    if m:
        out['width'], out['height'], out['depth'] = (int(x) for x in m.groups())
    w = re.match(r'\s*(\d{2,5})', facts.get('Вес') or '')
    if w:
        out['weight'] = int(w.group(1))
    return out


def facts_spec_kz(specs):
    """Габариты из карточки kz-каталога: «Ширина»: «1325 мм», «Вес облицовки»: «217.8 кг»."""
    out = {}
    for k, key in (('Ширина', 'width'), ('Высота', 'height'), ('Глубина', 'depth')):
        m = re.match(r'\s*(\d{2,5})', specs.get(k, ''))
        if m and int(m.group(1)) >= 100:
            out[key] = int(m.group(1))
    m = re.match(r'\s*(\d+(?:[.,]\d+)?)', specs.get('Вес облицовки', ''))
    if m:
        w = int(round(float(m.group(1).replace(',', '.'))))
        if w >= 5:
            out['weight'] = w
    return out


def stock_desc(facts, title, coll):
    """Описание заводской модели: топка, объём обогрева, дымоход, цвет.

    Шести позициям раздела выгрузка даёт один текст на всех — они
    отличаются только цветом глазури. Страница модели знает больше:
    какая в ней топка, на какой объём она рассчитана и какой нужен
    дымоход. Это то, что человек всё равно спросит первым.
    """
    box = (facts.get('Топка') or '').strip()
    heat = (facts.get('Обогрев') or '').strip()
    flue = re.sub(r'\s*мм$', '', (facts.get('Диаметр дымохода') or '').strip())
    if not box or not heat:
        return ''
    out = 'Заводская модель на топке %s: обогрев до %s м³' % (box, heat.split('-')[-1])
    if flue:
        out += ', дымоход %s мм' % flue
    colour = title.split(',', 1)[1].strip().lower() if ',' in title else ''
    # Модель обязана звучать: у «Дорфа» и «Ритма» есть версия в одном
    # и том же белом антике, и без названия оба текста совпадали.
    out += '. Облицовка изразцами%s%s.' % ((' ' + coll) if coll else '',
                                           (' в цвете ' + colour) if colour else '')
    return out + ' Комплект со склада, монтаж под ключ.'


def facts_desc(slug, facts, coll):
    """Описание из характеристик страницы объекта.

    Поле «цветовое решение» на сайте заполняют руками, и у части позиций
    там стоит чужая коллекция: под «Банным порталом Арт Нуво» написано
    «Изразцы Византия», под «Отопительной печью Прованс» — «Изразцы
    Элеганс». Это тот же след копипасты, что мы ловили в описаниях.
    Поэтому строку берём, только если названная в ней коллекция — своя.
    Расходится — оставляем заглушку: лучше общий текст, чем текст про
    другое изделие.
    """
    tail, use_firebox = FACT_TAIL.get(slug, ('', False))
    if not tail or not facts:
        return ''
    colour = (facts.get('Цветовое решение') or '').strip().rstrip('.')
    if not colour or len(colour) < 12:
        return ''
    if not coll:
        return ''
    # Поле «Коллекция» — второй сторож. У банного портала «Камея» оно
    # говорит «Прованс», а цветовое решение коллекцию не называет вовсе:
    # без этой проверки чужой текст прошёл бы незамеченным.
    site_coll = (facts.get('Коллекция') or '').lower()
    named = [c for c in CARD_COLLECTIONS if c.lower() in site_coll]
    if named and named[0].lower() != coll.lower():
        return ''
    low = colour.lower()
    alien = [c for c in CARD_COLLECTIONS
             if c.lower() in low and c.lower() != coll.lower()]
    if alien:
        return ''
    # На сайте размер набран то латинской «x», то кириллической «х».
    colour = re.sub(r'(\d)\s*[xх]\s*(\d)', r'\1×\2', colour)
    parts = []
    place = PLACING.get((facts.get('Тип расположения камина') or '').strip())
    if place:
        parts.append(place)
    if use_firebox:
        fb = FIREBOX.get((facts.get('Тип топки') or '').strip())
        if fb:
            parts.append(fb)
    out = colour + '.'
    if parts:
        out += ' ' + parts[0][0].upper() + parts[0][1:]
        if len(parts) > 1:
            out += ', ' + ', '.join(parts[1:])
        out += '.'
    return out + ' ' + tail


def assign_facts(slug, cards, positions):
    """Заполняем характеристиками только то, что осталось на заглушке.

    Две позиции одной коллекции в одном цвете дают дословно одинаковый
    текст, и поздний проход по дублям заменил бы обе общей заглушкой.
    Разводим их уточнением из названия — тем же, которым разведены сами
    названия.
    """
    table = OBJECT_SPECS.get(slug) or {}
    made = []
    for pos, c in zip(positions, cards):
        if not c.get('_gen') or c.get('_lock'):
            continue
        f = table.get(str(pos)) or {}
        # Печи-камины — заводские модели, и говорить о них надо не
        # коллекцией, а топкой и объёмом обогрева.
        v = stock_desc(f, c['title'], c.get('collection')) if slug == 'pechi-kaminy' else facts_desc(slug, f, c.get('collection'))
        if v:
            made.append((c, normalize_brand(clean_text(v, ''))))
    counts = {}
    for _, v in made:
        counts[v] = counts.get(v, 0) + 1
    for c, v in made:
        if counts[v] > 1 and ',' in (c.get('title') or ''):
            q = c['title'].split(',', 1)[1].strip()
            v = v.replace('.', ', %s.' % q, 1)
        c['desc'] = v
        c['_gen'] = False
    return cards


