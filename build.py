def localize(obj):
    """Глубокая копия описания направления с подстановкой страны.

    Строки: плейсхолдеры страны. Числа в калькуляторе: рублёвые цены
    (add, pricePerUnit, fixed) пересчитываются по курсу; строковые
    '@DORF_N@' и подобные — точные цены со старого сайта."""
    st = STOCK[CC['code']]
    exact = {'@DORF_N@': st['dorf'], '@RITM_N@': st['ritm'], '@PALETTE_N@': st['palette']}

    def walk(v, key=None):
        if isinstance(v, dict):
            return {k: walk(x, k) for k, x in v.items()}
        if isinstance(v, (list, tuple)):
            return [walk(x, key) for x in v]
        if isinstance(v, str):
            if v in exact:
                return exact[v]
            return country_text(v)
        if key in ('add', 'pricePerUnit', 'fixed') and isinstance(v, (int, float)) and v:
            return local(v)
        return v
    return walk(obj)


def local(rub, tile=False):
    """Цена в местной валюте из рублёвой: курс и округление страны."""
    step = CC["round_tile"] if tile else CC["round"]
    return int(round(rub * CC["rate"] / step) * step)


