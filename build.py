def _card_kind(slug, raw):
    low = (raw or '').lower()
    for needle, name in CARD_ALIAS:
        if needle in low:
            return name
    return CARD_KIND.get(slug, '')


def _card_qual(raw, used):
    low = (raw or '').lower()
    for needle, out in CARD_QUAL:
        if needle in low and out.lower() not in (used or '').lower():
            return out
    return ''


def card_title(slug, pos, raw, field):
    """Название по шаблону «тип изделия + коллекция»."""
    if (slug, pos) in CARD_OVERRIDE:
        return CARD_OVERRIDE[(slug, pos)]
    if (raw or '').startswith('http'):
        raw = ''
    # Изразцы — товарный каталог артикулов, а не объекты. Там название
    # уже содержит размер и фактуру, и шаблон «тип + коллекция» схлопнул
    # бы сто пять позиций одной коллекции в одну строку.
    if slug not in CARD_KIND:
        return _strip_art(raw)
    coll = card_collection(raw, field)
    if not coll:
        return _strip_art(raw)
    name = ('%s %s' % (_card_kind(slug, raw), coll)).strip()
    m = RE_COLOR.search(_strip_art(raw))
    if m:
        c = m.group(1).strip(' .,«»"')
        if c and c.lower() not in name.lower():
            name += ', %s' % c
    return name


def dedupe_titles(slug, rows):
    """Одинаковые названия разводим признаком из исходного текста.

    Признак добавляется всем членам столкнувшейся группы, а не только
    второму: иначе первый остаётся без уточнения и дубль сохраняется.
    """
    groups = {}
    for r in rows:
        groups.setdefault(r['title'], []).append(r)
    for name, grp in groups.items():
        if not name or len(grp) < 2:
            continue
        for r in grp:
            q = _card_qual(r['_raw'], name)
            if q:
                r['title'] = name + ', ' + q
    return rows


GEN = '\x00'   # метка «текст собран шаблоном», снимается при записи
STOP_WORDS = set('в во и на с со из для под по от у к а но или что это'.split())


def card_text(slug, raw_desc, raw_title, title, coll):
    """Описание: технические факты, дальше эпитеты.

    Живое описание из выгрузки информативнее шаблонного, поэтому его
    оставляем, если оно осмысленно. Пустые, ссылочные и пересказывающие
    заголовок — заменяем шаблоном по направлению.

    Пересказ ловим по словам: если, выкинув служебные, описание не
    добавляет к заголовку хотя бы четырёх новых слов, читателю оно
    ничего не сообщает («Барбекю комплекс Версаль» и под ним
    «Барбекю комплекс в изразцовой облицовке Версаль»).
    """
    v = normalize_brand(clean_text(raw_desc, ''))
    v = _strip_art(v.split('|')[0].strip())
    low = v.strip().lower()
    words = set(re.findall(r'[а-яёa-z]+', low)) - STOP_WORDS
    known = set(re.findall(r'[а-яёa-z]+', (title or '').lower())) - STOP_WORDS
    # Описание, называющее чужую коллекцию, пришло от другой позиции:
    # в выгрузке все шесть печей-каминов получили текст про «Дорф».
    alien = any(c.lower() in low for c in CARD_COLLECTIONS
                if c.lower() != (coll or '').lower())
    # …или чужой цвет: «Дорф в цвете Белый Антик» под карточкой
    # «Дорф, Муравленый» — тоже след копипасты из админки.
    mc = RE_COLOR.search(v)
    if mc and mc.group(1).strip().lower() not in (title or '').lower():
        alien = True
    bad = (not v or len(v) < 25 or low.startswith('http') or alien
           or low == (raw_title or '').strip().lower()
           or len(words - known) < 4)
    if not bad:
        return v
    tpl = CARD_DESC_TPL.get(slug)
    if slug not in CARD_KIND:
        return v or GEN + FALLBACK_DESC.get(slug, '')
    if tpl and coll:
        # Уточнение из названия переносим в описание: без него две
        # карточки одной коллекции получают дословно одинаковый текст,
        # и поздний проход по дублям заменяет обе общей заглушкой.
        extra = ''
        if ',' in (title or ''):
            q = title.split(',', 1)[1].strip().lower()
            # Цвет требует слова «цвет», иначе выходит «облицовка, болотный».
            extra = (', цвет %s' % q) if 'цвет' in (raw_title or '').lower() else ', %s' % q
        return GEN + tpl.replace('«%s»', '«%s»' + extra) % coll
    return GEN + FALLBACK_DESC.get(slug, '')


def fmt_ru(n):
    """Число с неразрывными пробелами по разрядам."""
    return '{:,}'.format(int(n)).replace(',', '\u00a0')


