def money_short(n):
    """Сумма коротко для подписи фильтра: «2,4 млн ₸», «18 тыс BYN», «7 150 ₸»."""
    cur = CC['currency']
    if n >= 1_000_000:
        v = n / 1_000_000
        return ('%.1f' % v).rstrip('0').rstrip('.').replace('.', ',') + ' млн ' + cur
    if n >= 10_000:
        return str(int(round(n / 1000))) + ' тыс ' + cur
    return fmt_ru(n) + ' ' + cur


def price_filter(cards):
    ps = sorted(c['p1'] for c in cards if c.get('p1'))
    if len(ps) < 6:
        return []
    a, b = ps[len(ps) // 3], ps[2 * len(ps) // 3]
    step = CC['round'] if a >= 100_000 else CC['round_tile']
    a = int(round(a / step) * step); b = int(round(b / step) * step)
    if a >= b:
        return []
    return [('до ' + money_short(a), 0, a), (money_short(a) + ' – ' + money_short(b), a, b), ('от ' + money_short(b), b, 10**12)]


def no_orphan(html):
    """Склеивает два последних слова каждой строки заголовка неразрывным пробелом.
    Без этого на узком экране последнее слово остаётся одно на строке —
    самая заметная типографская ошибка на первом экране."""
    def fix(seg):
        parts = re.split(r'(<[^>]+>)', seg)
        idx = [i for i, x in enumerate(parts) if not x.startswith('<') and x.strip()]
        if not idx:
            return seg
        last = idx[-1]
        words = parts[last].rstrip()
        m = re.search(r'(\S+)(\s+)(\S+\s*)$', words)
        if m:
            parts[last] = words[:m.start()] + m.group(1) + '&nbsp;' + m.group(3)
        return ''.join(parts)
    return '<br>'.join(fix(x) for x in html.split('<br>'))

