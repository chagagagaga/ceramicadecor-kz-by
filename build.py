def shell_parts():
    """Шапка, подвал, док, панель и скрипты — вырезаем из INDEX_TPL."""
    head = INDEX_TPL[:INDEX_TPL.index('</head>')]
    header = INDEX_TPL[INDEX_TPL.index('<header class="header" data-header>'):INDEX_TPL.index('<main id="top">')]
    tail = INDEX_TPL[INDEX_TPL.index('<footer class="footer">'):]
    return head, header, tail


